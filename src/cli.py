# Config paths
AXENG_HOME = Path(os.getenv("AXENG_HOME", Path.home() / ".axeng"))
CONFIG_FILE = AXENG_HOME / "config.json"
ENV_FILE = AXENG_HOME / ".env"

def load_config() -> dict:
    """Load existing configuration"""
    if CONFIG_FILE.exists():
        return json.loads(CONFIG_FILE.read_text())
    return {}

def save_config(config: dict):
    """Save configuration"""
    AXENG_HOME.mkdir(parents=True, exist_ok=True)
    CONFIG_FILE.write_text(json.dumps(config, indent=2))

def update_env_file(config: dict):
    """Update .env file from config"""
    env_lines = []

    # Header
    env_lines.append("# Axeng Configuration")
    env_lines.append("# Generated by: axeng configure")
    env_lines.append("")

    # LLM Provider
    if config.get("llm_provider"):
        provider = config["llm_provider"]
        env_lines.append("# LLM Provider")
        env_lines.append(f"LLM_PROVIDER_ORDER={provider}")

        if provider == "opencode":
            env_lines.append(f"OPENCODE_API_KEY={config.get('opencode_api_key', '')}")
            env_lines.append(f"OPENCODE_MODEL={config.get('opencode_model', 'minimax-m2.5-free')}")
        elif provider == "anthropic":
            env_lines.append(f"ANTHROPIC_API_KEY={config.get('anthropic_api_key', '')}")
        elif provider == "openai":
            env_lines.append(f"OPENAI_API_KEY={config.get('openai_api_key', '')}")
        env_lines.append("")

    # GitHub
    if config.get("github_token"):
        env_lines.append("# GitHub")
        env_lines.append(f"GITHUB_TOKEN={config['github_token']}")
        env_lines.append("")

    # Linear
    if config.get("linear_api_key"):
        env_lines.append("# Linear")
        env_lines.append(f"LINEAR_API_KEY={config['linear_api_key']}")
        env_lines.append("")

    # Telegram (optional)
    if config.get("telegram_bot_token"):
        env_lines.append("# Telegram")
        env_lines.append(f"TELEGRAM_BOT_TOKEN={config['telegram_bot_token']}")
        env_lines.append(f"TELEGRAM_CHAT_ID={config.get('telegram_chat_id', '')}")
        env_lines.append("")

    # Google (optional)
    if config.get("google_enabled"):
        env_lines.append("# Google Workspace")
        env_lines.append("GOOGLE_CLIENT_SECRET=~/.hermes/secrets/google_client_secret.json")
        env_lines.append("GOOGLE_TOKEN_PATH=~/.hermes/secrets/google_token.json")
        env_lines.append("")

    ENV_FILE.write_text("\n".join(env_lines))

@app.command()
def configure():
    """
    Interactive configuration wizard for Axeng
    """
    console.print(Panel.fit(
        "[bold cyan]Axeng Configuration Wizard[/bold cyan]\n"
        "Let's set up your AI chief of staff",
        border_style="cyan"
    ))
    console.print()

    config = load_config()

    # Step 1: LLM Provider
    console.print("[bold]Step 1: Choose your LLM provider[/bold]")
    console.print("Axeng needs an AI model to generate reports and insights.\n")

    llm_choice = Prompt.ask(
        "Which provider would you like to use?",
        choices=["opencode", "anthropic", "openai", "groq"],
        default=config.get("llm_provider", "opencode")
    )
    config["llm_provider"] = llm_choice

    # Get API key for chosen provider
    if llm_choice == "opencode":
        console.print("\n[cyan]OpenCode Zen[/cyan] - Free models available!")
        console.print("Get your API key at: https://opencode.ai/")
        api_key = Prompt.ask(
            "OpenCode API key",
            default=config.get("opencode_api_key", ""),
            password=True
        )
        config["opencode_api_key"] = api_key

        model = Prompt.ask(
            "Model",
            default=config.get("opencode_model", "minimax-m2.5-free"),
            choices=["minimax-m2.5-free", "deepseek-v4-flash-free", "big-pickle"]
        )
        config["opencode_model"] = model

    elif llm_choice == "anthropic":
        console.print("\n[cyan]Anthropic Claude[/cyan] - Best quality")
        console.print("Get your API key at: https://console.anthropic.com/")
        api_key = Prompt.ask(
            "Anthropic API key",
            default=config.get("anthropic_api_key", ""),
            password=True
        )
        config["anthropic_api_key"] = api_key

    elif llm_choice == "openai":
        console.print("\n[cyan]OpenAI[/cyan] - Most compatible")
        console.print("Get your API key at: https://platform.openai.com/")
        api_key = Prompt.ask(
            "OpenAI API key",
            default=config.get("openai_api_key", ""),
            password=True
        )
        config["openai_api_key"] = api_key

    console.print("\n[green]✓[/green] LLM provider configured\n")

    # Step 2: GitHub
    console.print("[bold]Step 2: GitHub integration[/bold]")
    console.print("Connect to GitHub to track repos, PRs, and issues.\n")

    github_token = Prompt.ask(
        "GitHub token (or press Enter to use 'gh' CLI)",
        default=config.get("github_token", ""),
        password=True
    )
    if github_token:
        config["github_token"] = github_token
    else:
        console.print("[dim]Will use GitHub CLI (gh auth login)[/dim]")

    console.print("[green]✓[/green] GitHub configured\n")

    # Step 3: Linear
    console.print("[bold]Step 3: Linear integration[/bold]")
    console.print("Connect to Linear to manage issues and projects.\n")
    console.print("Get your API key at: https://linear.app/settings/api\n")

    linear_key = Prompt.ask(
        "Linear API key",
        default=config.get("linear_api_key", ""),
        password=True
    )
    config["linear_api_key"] = linear_key

    console.print("[green]✓[/green] Linear configured\n")

    # Step 4: Optional services
    console.print("[bold]Step 4: Optional services[/bold]\n")

    # Telegram
    if Confirm.ask("Set up Telegram notifications?", default=config.get("telegram_bot_token") is not None):
        console.print("\nTalk to @BotFather on Telegram to create a bot\n")
        bot_token = Prompt.ask(
            "Telegram bot token",
            default=config.get("telegram_bot_token", ""),
            password=True
        )
        chat_id = Prompt.ask(
            "Telegram chat ID",
            default=config.get("telegram_chat_id", "")
        )
        config["telegram_bot_token"] = bot_token
        config["telegram_chat_id"] = chat_id
        console.print("[green]✓[/green] Telegram configured")

    # Google
    if Confirm.ask("\nSet up Google Calendar integration?", default=config.get("google_enabled", False)):
        console.print("\n[cyan]Google Workspace Setup:[/cyan]")
        console.print("1. Go to https://console.cloud.google.com/")
        console.print("2. Enable Calendar API + Gmail API")
