        console.print("4. Download and save to ~/.hermes/secrets/google_client_secret.json")
        console.print("")

        if Confirm.ask("Have you saved the client secret?"):
            config["google_enabled"] = True
            console.print("[green]✓[/green] Google workspace enabled")
            console.print("[dim]Run 'axeng google auth' to complete setup[/dim]")

